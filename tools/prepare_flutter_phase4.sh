#!/usr/bin/env bash
set -euo pipefail

# Run from the project root on a machine with Flutter SDK and Android SDK installed.
# This script creates a genuine Flutter add-to-app module and copies the reviewed UI.
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FLUTTER_BIN="${FLUTTER_BIN:-flutter}"
MODULE="$ROOT/flutter_module"

if ! command -v "$FLUTTER_BIN" >/dev/null 2>&1; then
  echo "ERROR: Flutter SDK is not available. Install Flutter and ensure '$FLUTTER_BIN' is on PATH." >&2
  exit 2
fi

"$FLUTTER_BIN" --version

if [[ ! -f "$MODULE/pubspec.yaml" ]]; then
  "$FLUTTER_BIN" create --template module --org com.example "$MODULE"
fi

# Keep the standalone UI and widget tests as the source of truth.
# The generated module's default widget_test.dart still references MyApp; if
# left in place, it fails after the module's lib/ is replaced by App Guard UI.
rm -rf "$MODULE/lib" "$MODULE/test"
cp -R "$ROOT/flutter_ui/lib" "$MODULE/lib"
if [[ -d "$ROOT/flutter_ui/test" ]]; then
  cp -R "$ROOT/flutter_ui/test" "$MODULE/test"
fi
# Keep the generated module pubspec.yaml: it contains required `module:` metadata.

# The add-to-app module has its own Android wrapper generated by Flutter. Keep the
# native bridge in host sources, not inside generated module files.
mkdir -p "$ROOT/app/src/flutter/java/com/example/flutterbridge" "$ROOT/app/src/main/java/com/example/flutterbridge"
cp "$ROOT/flutter_ui/android_host/com/example/flutterbridge/AppGuardFlutterBridge.kt" \
   "$ROOT/app/src/flutter/java/com/example/flutterbridge/AppGuardFlutterBridge.kt"
cp "$ROOT/flutter_ui/android_host/com/example/flutterbridge/AppGuardFlutterActivity.kt" \
   "$ROOT/app/src/flutter/java/com/example/flutterbridge/AppGuardFlutterActivity.kt"
cp "$ROOT/flutter_ui/android_host/com/example/flutterbridge/FlutterHostEntryActivity.kt" \
   "$ROOT/app/src/main/java/com/example/flutterbridge/FlutterHostEntryActivity.kt"

python3 - "$ROOT" <<'PY'
from pathlib import Path
import sys
root = Path(sys.argv[1])
settings = root / 'settings.gradle.kts'
text = settings.read_text()
marker = '// BEGIN OPTIONAL FLUTTER ADD-TO-APP INTEGRATION'
if marker not in text:
    text += '''\n\n// BEGIN OPTIONAL FLUTTER ADD-TO-APP INTEGRATION\n// Enable with -PenableFlutterHost=true after running tools/prepare_flutter_phase4.sh\nif (providers.gradleProperty("enableFlutterHost").orNull == "true") {\n    val flutterModule = file("flutter_module")\n    val includeScript = flutterModule.resolve(".android/include_flutter.groovy")\n    require(includeScript.isFile) { "Flutter module is missing. Run tools/prepare_flutter_phase4.sh first." }\n    apply(from = includeScript)\n}\n// END OPTIONAL FLUTTER ADD-TO-APP INTEGRATION\n'''
    settings.write_text(text)

app_build = root / 'app/build.gradle.kts'
text = app_build.read_text()
marker = '// BEGIN OPTIONAL FLUTTER HOST SOURCE/DEPENDENCY'
if marker not in text:
    text += '''\n\n// BEGIN OPTIONAL FLUTTER HOST SOURCE/DEPENDENCY\nval enableFlutterHost = providers.gradleProperty("enableFlutterHost").orNull == "true"\nif (enableFlutterHost) {\n    android.sourceSets.getByName("main").java.srcDir("src/flutter/java")\n}\n// END OPTIONAL FLUTTER HOST SOURCE/DEPENDENCY\n'''
# Dependency is added after the dependencies block so default builds remain native-only.
if 'OPTIONAL FLUTTER PROJECT DEPENDENCY' not in text:
    text += '''\n\n// OPTIONAL FLUTTER PROJECT DEPENDENCY\nif (enableFlutterHost) {\n    dependencies.add("implementation", project(":flutter"))\n}\n'''
app_build.write_text(text)

manifest = root / 'app/src/main/AndroidManifest.xml'
text = manifest.read_text()
activity = 'android:name=".flutterbridge.AppGuardFlutterActivity"'
if activity not in text:
    insert = '''
        <!-- Optional Flutter entry; native MainActivity remains the launcher. -->
        <activity
            android:name=".flutterbridge.FlutterHostEntryActivity"
            android:exported="false"
            android:label="حارس التطبيقات - Flutter"
            android:theme="@style/Theme.MyApplication" />
        <activity
            android:name=".flutterbridge.AppGuardFlutterActivity"
            android:exported="false"
            android:label="حارس التطبيقات - Flutter Host"
            android:theme="@style/Theme.MyApplication" />
'''
    text = text.replace('        <!-- Lock Screen Overlay Activity -->', insert + '\n        <!-- Lock Screen Overlay Activity -->')
    manifest.write_text(text)
PY

python3 "$ROOT/tools/activate_flutter_launcher.py" "$ROOT"

cat <<'MSG'
Flutter module prepared.
Next, validate in this order:
  (cd flutter_module && flutter pub get)
  ./gradlew -PenableFlutterHost=true :app:assembleDebug
Flutter becomes the main dashboard after native PIN/onboarding gates. Test accessibility and Recents on-device before release.
MSG
